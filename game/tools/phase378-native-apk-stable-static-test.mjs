const activity = read('native/android/app/src/main/java/com/svrpoker/app/MainActivity.java');
const fallback = read('native/android/app/src/main/assets/fallback.html');
const gameManifest = JSON.parse(read('game/manifest.json'));
const release = JSON.parse(read('game/android-release.json'));
const update = JSON.parse(read('update/app-version.json'));

assert.match(root, /PHASE-378-PUBLIC-APK-RC2-NOTIFICATION-LOCK/);
