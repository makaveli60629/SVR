assert.match(stable, /PHASE-378-ANDROID-STANDALONE-STABLE-TABLE-LOCK/);
assert.match(stable, /id="join"[\s\S]*JOIN NOW/);
assert.match(stable, /No cards are dealt on this screen/);
assert.doesNotMatch(stable, /type="module"|three\.module|main\.js/);
assert.match(legacy, /android-stable\.html\?v=phase378/);
assert.match(oldPlay, /android-stable\.html\?v=phase378/);
assert.match(downloads, /DOWNLOAD SVR POKER APK RC2/);
assert.match(downloads, /Uninstall the old SVR Poker APK/);
assert.match(counter, /NEW ANDROID APK RC2/);
assert.match(counter, /svr-poker-android-rc2\.apk/);
assert.match(updater, /DOWNLOAD APK RC2/);
assert.match(gradle, /versionCode 2/);
assert.match(gradle, /versionName '0\.1\.0-rc2'/);
assert.match(gradle, /buildTypes[\s\S]*debug/);
assert.doesNotMatch(gradle, /storePassword|keyPassword|storeFile/);
assert.match(activity, /android-stable\.html\?v=phase378/);
assert.match(activity, /LOAD_NO_CACHE/);
